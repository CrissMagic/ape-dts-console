// Unknown server codes remain visible instead of being mislabeled as success.
export function operationLabel(code: string): string {
  return labels[code] === undefined ? code : `${labels[code]}（${code}）`;
}

export function operationName(code: string): string {
  return labels[code] ?? code;
}

